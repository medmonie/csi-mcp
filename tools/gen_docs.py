"""Write the action references from the catalogue (the same text and parameter details Claude sees):
docs/ACTIONS-ETABS.md, docs/ACTIONS-SAP2000.md, docs/ACTIONS-SAFE.md (one per edition) and docs/ACTIONS.md (index).
package_editions.py puts each edition's page in its package as ACTIONS.md."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "server"))
import catalog  # noqa: E402
import edition  # noqa: E402


def actions_markdown() -> str:
    prog = edition.current()
    tool = edition.server_name()
    lines = [f"# {prog or 'CSI'} MCP actions (server {catalog.SERVER_VERSION})", "",
             "Generated by tools/gen_docs.py from server/catalog.py and server/actions.py - do not edit by hand.", "",
             f"Call the `{tool}` tool with `action` and `params`. With `CSI_MCP_SPLIT=1` the read actions are on "
             f"`{tool}_read` and the edit actions on `{tool}_edit`.", "",
             "> " + catalog.software_note(), ">", "> " + catalog.UNITS_NOTE, ">", "> " + catalog.NO_DESIGN_NOTE, ">",
             "> " + catalog.LOCK_NOTE, ""]
    data = catalog.help_data()
    for title, key in (("Read actions", "readActions"), ("Edit actions", "editActions")):
        lines += [f"## {title}", ""]
        for name, entry in data[key].items():
            lines += [f"### `{name}`", "", entry["summary"], ""]
            if entry["params"]:
                lines += ["| parameter | required | default | description |", "|---|---|---|---|"]
                for p, d in entry["params"].items():
                    desc = d["description"].replace("|", "\\|")
                    if d.get("one_of"):
                        desc += " (one of: " + ", ".join(map(str, d["one_of"])) + ")"
                    default = "" if d["required"] else f"`{d.get('default')}`"
                    lines.append(f"| `{p}` | {'yes' if d['required'] else ''} | {default} | {desc} |")
                lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    docs = ROOT / "docs"
    index = [f"# CSI MCP actions (server {catalog.SERVER_VERSION})", "",
             "One MCP server per program since 0.7.0; each lists only what its program's API can do:", ""]
    for prog in edition.ALL:
        edition.force(prog)
        name = f"ACTIONS-{prog}.md"
        (docs / name).write_text(actions_markdown(), encoding="utf-8")
        data = catalog.help_data()
        n = len(data["readActions"]) + len(data["editActions"])
        index.append(f"- [{prog}]({name}): tool `{prog.lower()}`, {n} actions + help")
    edition.force(None)
    (docs / "ACTIONS.md").write_text("\n".join(index) + "\n", encoding="utf-8")
    print("docs/ACTIONS*.md written")


if __name__ == "__main__":
    main()
